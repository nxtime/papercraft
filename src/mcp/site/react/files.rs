//! The files both project shapes share: `lib/site.ts` (the site as data plus the head
//! computation), the message catalogs, `public/` and `package.json`.

use super::styles::{Deps, Kit};
use super::{Ctx, Files, js, put};
use crate::mcp::site::model::mime;
use crate::mcp::site::style::class_slug;
use serde_json::{Map, Value, json};
use std::collections::BTreeSet;

pub fn shared(cx: &Ctx, kit: &Kit, files: &mut Files) -> Result<(), String> {
    let p = cx.prefix();
    put(files, &format!("{p}lib/site.ts"), site_ts(cx));
    if cx.multi {
        messages(cx, files)?;
    }
    public(cx, files);
    put(files, "package.json", package_json(cx, kit)?);
    Ok(())
}

fn site_ts(cx: &Ctx) -> String {
    let site = cx.site;
    let list = |items: Vec<String>| items.join(", ");
    let mut s = String::from("// Generated by PaperCraft export_site.\n");
    s.push_str(&format!(
        "export const SITE_TITLE = {}\n",
        js(&site.site_title)
    ));
    s.push_str(&format!("/** The public address, or empty when no base_url was given (addresses are then root relative). */\nexport const SITE = {}\n\n", js(site.base_url.as_deref().unwrap_or_default())));
    s.push_str("export type LocaleInfo = { dir: string; tag: string | null; label: string; cls: string | null; hreflang: boolean }\nexport const locales: readonly LocaleInfo[] = [\n");
    for l in &site.locales {
        let opt = |v: &Option<String>| v.as_deref().map_or("null".to_owned(), js);
        s.push_str(&format!(
            "  {{ dir: {}, tag: {}, label: {}, cls: {}, hreflang: {} }},\n",
            js(l.folder.as_deref().unwrap_or_default()),
            opt(&l.tag),
            js(&l.label),
            opt(&l.class),
            l.hreflang
        ));
    }
    s.push_str("]\n\nexport type PageInfo = { path: string; title: readonly string[]; description: readonly string[] }\nexport const pages: readonly PageInfo[] = [\n");
    for (i, p) in site.pages.iter().enumerate() {
        let path = if i == 0 {
            String::new()
        } else {
            format!("{}/", p.stem)
        };
        let strs = |v: &[String]| format!("[{}]", list(v.iter().map(|t| js(t)).collect()));
        s.push_str(&format!(
            "  {{ path: {}, title: {}, description: {} }},\n",
            js(&path),
            strs(&p.title),
            strs(&p.description)
        ));
    }
    s.push_str("]\n\n");
    if let Some(face) = site.style.preload.and_then(|i| site.style.fonts.get(i)) {
        s.push_str(&format!(
            "export const FONT_URL = {}\nexport const FONT_TYPE = {}\n\n",
            js(&format!("/{}", face.path)),
            js(&mime(&face.path, "font"))
        ));
    }
    // Vite's index.html links the icon itself.
    if cx.next {
        s.push_str(&format!(
            "export const ICON = {}\n\n",
            js(&site.icon_href("/"))
        ));
    }
    s.push_str(SITE_TS_TAIL);
    s
}

const SITE_TS_TAIL: &str = "/** The address of a page in a locale, with a trailing slash. */
export const href = (loc: number, page: number) => (locales[loc].dir ? `/${locales[loc].dir}/` : '/') + pages[page].path

export const localeIndex = (dir: string) => Math.max(0, locales.findIndex((l) => l.dir === dir))

/** What a page puts in <head>, besides the font preload. */
export function headData(loc: number, page: number) {
  const p = pages[page]
  const url = (to: number) => SITE + href(to, page)
  const langs = locales.flatMap((l, i) => (l.hreflang ? [i] : []))
  const tag = (i: number) => locales[i].tag ?? ''
  const alternates: [string, string][] = langs.map((i) => [tag(i), url(i)])
  if (langs.length > 0) alternates.push(['x-default', url(langs[0])])
  const og = (t: string) => t.split('-').join('_')
  const own = locales[loc].tag
  return {
    title: p.title[loc],
    description: p.description[loc],
    canonical: url(loc),
    alternates,
    ogLocale: own ? og(own) : null,
    ogAlternates: langs.filter((i) => i !== loc).map((i) => og(tag(i))),
    ogUrl: SITE ? url(loc) : null,
  }
}

/** The language index at `/`. */
export function indexHeadData() {
  const langs = locales.flatMap((l, i) => (l.hreflang ? [i] : []))
  const url = (i: number) => SITE + `/${locales[i].dir}/`
  const alternates: [string, string][] = langs.map((i) => [locales[i].tag ?? '', url(i)])
  if (langs.length > 0) alternates.push(['x-default', url(langs[0])])
  return { title: SITE_TITLE, description: 'Choose a version of this site.', canonical: SITE + '/', alternates }
}
";

/// One catalog per locale with every key in all of them, so the types agree.
fn messages(cx: &Ctx, files: &mut Files) -> Result<(), String> {
    let site = cx.site;
    let keys: BTreeSet<&String> = site.messages.iter().flat_map(|m| m.keys()).collect();
    let mut imports = String::new();
    let mut names = Vec::new();
    for (i, l) in site.locales.iter().enumerate() {
        let dir = l.folder.as_deref().unwrap_or_default();
        let cat: Map<String, Value> = keys
            .iter()
            .map(|k| {
                (
                    (*k).clone(),
                    json!(site.messages[i].get(*k).cloned().unwrap_or_default()),
                )
            })
            .collect();
        let mut body =
            serde_json::to_string_pretty(&Value::Object(cat)).map_err(|e| e.to_string())?;
        body.push('\n');
        put(files, &format!("{}messages/{dir}.json", cx.prefix()), body);
        imports.push_str(&format!(
            "import c{i} from {}\n",
            js(&format!("../messages/{dir}.json"))
        ));
        names.push(format!("c{i}"));
    }
    let ts = format!(
        "{imports}\nexport type Messages = typeof c0\nexport const catalogs: readonly Messages[] = [{}]\n",
        names.join(", ")
    );
    put(files, &format!("{}lib/messages.ts", cx.prefix()), ts);
    Ok(())
}

fn public(cx: &Ctx, files: &mut Files) {
    let site = cx.site;
    for (path, bytes) in &site.assets {
        files.insert(format!("public/{path}"), bytes.clone());
    }
    put(files, "public/robots.txt", site.robots());
    let Some(base) = &site.base_url else { return };
    let abs = |loc: usize, page: usize| format!("{base}{}", cx.route(loc, page));
    put(
        files,
        "public/sitemap.xml",
        site.sitemap(&abs, cx.multi.then(|| format!("{base}/"))),
    );
}

fn package_json(cx: &Ctx, kit: &Kit) -> Result<String, String> {
    let (extra, extra_dev) = kit.deps();
    let (mut deps, mut dev, scripts): (Deps, Deps, Value) = if cx.next {
        (
            vec![
                ("next", "16.4.5"),
                ("react", "19.3.0"),
                ("react-dom", "19.3.0"),
            ],
            vec![
                ("@types/node", "^20"),
                ("@types/react", "^19"),
                ("@types/react-dom", "^19"),
                ("typescript", "^5"),
            ],
            json!({"dev": "next dev", "build": "next build && node scripts/flatten-prefetch.mjs"}),
        )
    } else {
        (
            vec![
                ("react", "^19.3.1"),
                ("react-dom", "^19.3.1"),
                ("react-router", "^8.5.1"),
            ],
            vec![
                ("@types/node", "^24.19.2"),
                ("@types/react", "^19.3.0"),
                ("@types/react-dom", "^19.3.0"),
                ("@vitejs/plugin-react", "^6.1.2"),
                ("typescript", "~7.0.2"),
                ("vite", "^8.3.6"),
            ],
            json!({"dev": "vite", "build": "tsc -b && vite build", "preview": "vite preview"}),
        )
    };
    deps.extend(extra);
    dev.extend(extra_dev);
    let map = |v: Deps| -> Value {
        Value::Object(
            v.into_iter()
                .map(|(k, v)| (k.to_owned(), json!(v)))
                .collect(),
        )
    };
    let mut pkg = json!({"name": class_slug(&cx.site.site_title), "version": "0.1.0", "private": true, "scripts": scripts, "dependencies": map(deps), "devDependencies": map(dev)});
    if !cx.next {
        pkg["type"] = json!("module");
    }
    let mut text = serde_json::to_string_pretty(&pkg).map_err(|e| e.to_string())?;
    text.push('\n');
    Ok(text)
}
